    function t(key, fallback = "") {
        const lang = getCurrentLang();
        return (AERO_I18N[lang] && AERO_I18N[lang][key]) || AERO_I18N.vi[key] || fallback || key;
    }

    function getLocalizedField(item, baseField, fallback = "") {
        const lang = getCurrentLang();
        if (!item) return fallback;

        const localized = lang === "en"
            ? item[`${baseField}En`] || item[`${baseField}_en`] || item?.translations?.en?.[baseField]
            : item[`${baseField}Vi`] || item[`${baseField}_vi`] || item?.translations?.vi?.[baseField];

        let value = safeText(localized, "");

        if (!value && lang === "en" && baseField === "title") {
            const originalTitle = safeText(item.title || item.name || item.promotionTitle || item.voucherName, "");
            value = NEWS_TITLE_FALLBACK_EN[originalTitle.toUpperCase()] || "";
        }

        if (!value && lang === "en" && baseField === "title") {
            value = safeText(item.originalTitle || item.nameEn, "");
        }

        if (!value) value = safeText(item[baseField], fallback);
        return safeText(value, fallback);
    }

    function translateElement(el, key, html) {
        const value = t(key);
        if (html || key.endsWith("_html")) {
            el.innerHTML = value;
        } else {
            el.textContent = value;
        }
    }

    function updateLanguageSwitcherUI(lang) {
        const viBtn = document.getElementById("lang-toggle-vi") || document.getElementById("langVi");
        const enBtn = document.getElementById("lang-toggle-en") || document.getElementById("langEn");
        if (viBtn) {
            viBtn.classList.toggle("active", lang === "vi");
            viBtn.setAttribute("aria-pressed", String(lang === "vi"));
        }
        if (enBtn) {
            enBtn.classList.toggle("active", lang === "en");
            enBtn.setAttribute("aria-pressed", String(lang === "en"));
        }
        document.querySelectorAll(".lang-switch [data-lang]").forEach(btn => {
            btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
        });
    }

    function applyLanguage(lang) {
        const currentLang = persistLang(lang || getCurrentLang());
        document.documentElement.lang = currentLang;

        document.querySelectorAll("[data-i18n]").forEach(el => {
            translateElement(el, el.getAttribute("data-i18n"), el.hasAttribute("data-i18n-html"));
        });

        document.querySelectorAll("[data-translate]").forEach(el => {
            translateElement(el, el.getAttribute("data-translate"), el.hasAttribute("data-translate-html"));
        });

        document.querySelectorAll("[data-i18n-placeholder], [data-translate-placeholder]").forEach(el => {
            const key = el.getAttribute("data-i18n-placeholder") || el.getAttribute("data-translate-placeholder");
            el.setAttribute("placeholder", t(key));
        });

        document.querySelectorAll("[data-i18n-title], [data-translate-title]").forEach(el => {
            const key = el.getAttribute("data-i18n-title") || el.getAttribute("data-translate-title");
            el.setAttribute("title", t(key));
        });

        updateLanguageSwitcherUI(currentLang);
        document.dispatchEvent(new CustomEvent("aero:languageApplied", { detail: { lang: currentLang } }));
        window.dispatchEvent(new CustomEvent("aero:languageApplied", { detail: { lang: currentLang } }));
    }

    function setLanguage(lang) {
        const currentLang = persistLang(lang);
        applyLanguage(currentLang);

        if (window.updateUserLanguageInFirestore) {
            window.updateUserLanguageInFirestore(currentLang);
        }

        document.dispatchEvent(new CustomEvent("aero:languageChanged", { detail: { lang: currentLang } }));
        window.dispatchEvent(new CustomEvent("aero:languageChanged", { detail: { lang: currentLang } }));
    }

    function translateDynamic(value, type) {
        if (getCurrentLang() !== "en" || value === null || value === undefined) return value;
        const raw = String(value);
        const map = DYNAMIC_MAPS[type] || {};
        if (map[raw]) return map[raw];
        if (type === "genre") {
            return raw.split(",").map(item => map[item.trim()] || item.trim()).join(", ");
        }
        return raw;
    }

    function formatLocalizedDate(value) {
        if (!value) return t("updating");
        try {
            const date = value.toDate ? value.toDate() : new Date(value);
            if (Number.isNaN(date.getTime())) return String(value);
            return date.toLocaleDateString(getCurrentLang() === "en" ? "en-US" : "vi-VN");
        } catch {
            return String(value);
        }
    }

    function formatLocalizedCurrency(value) {
        const amount = Number(value || 0);
        return getCurrentLang() === "en"
            ? amount.toLocaleString("en-US") + " VND"
            : amount.toLocaleString("vi-VN") + "đ";
    }


    function normalizeLang(lang) {
        return lang === "en" ? "en" : "vi";
    }

    function getCurrentLang() {
        return normalizeLang(localStorage.getItem("aero_lang") || localStorage.getItem("language") || "vi");
    }

    function persistLang(lang) {
        const target = normalizeLang(lang);
        localStorage.setItem("aero_lang", target);
        localStorage.setItem("language", target);
        return target;
    }

    function safeText(value, fallback = "") {
        if (value === undefined || value === null) return fallback;
        const text = String(value).trim();
        if (!text || text.toLowerCase() === "undefined" || text.toLowerCase() === "null" || text === "NaN" || text === "Invalid Date") {
            return fallback;
        }
        return text;
    }

